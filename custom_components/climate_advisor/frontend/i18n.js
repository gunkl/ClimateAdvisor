  function detectLang() {
    try {
      var qs = /(?:^|[?&])lang=(fr|en)(?:&|$)/.exec(location.search || '');
      if (qs) return qs[1];
    } catch (e) { /* ignore */ }
    try {
      var saved = localStorage.getItem('climate_advisor_lang');
      if (saved === 'fr' || saved === 'en') return saved;
    } catch (e) { /* private mode */ }
    var nav = ((navigator.language || navigator.userLanguage || 'en') + '').toLowerCase();
    return nav.indexOf('fr') === 0 ? 'fr' : 'en';
  }

  var LANG = detectLang();

  function t(key, vars) {
    var dict = STR[LANG] || STR.en;
    var s = dict[key];
    if (s == null) s = STR.en[key] != null ? STR.en[key] : key;
    if (vars) {
      Object.keys(vars).forEach(function (k) {
        s = s.split('{' + k + '}').join(vars[k]);
      });
    }
    return s;
  }

  var ATTRS = ['title', 'placeholder', 'aria-label', 'value'];

  function apply(root) {
    root = root || document;
    var nodes = root.querySelectorAll('[data-i18n]');
    for (var i = 0; i < nodes.length; i++) {
      nodes[i].textContent = t(nodes[i].getAttribute('data-i18n'));
    }
    ATTRS.forEach(function (attr) {
      var sel = '[data-i18n-' + attr + ']';
      var els = root.querySelectorAll(sel);
      for (var j = 0; j < els.length; j++) {
        els[j].setAttribute(attr, t(els[j].getAttribute('data-i18n-' + attr)));
      }
    });
  }

  window.CA_I18N = { lang: LANG, t: t, apply: apply };
  document.documentElement.lang = LANG;
