"""The Python CLDR plural rules equal Node's ``Intl.PluralRules`` (Issue #1341 drift check).

``tests/fixtures/i18n_plural_table.json`` is generated by ``tools/i18n_conformance_gen.mjs``; regenerate it (and
review the diff) whenever the pinned Node/ICU/CLDR changes.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from custom_components.climate_advisor import i18n

TABLE = json.loads((Path(__file__).parent / "fixtures" / "i18n_plural_table.json").read_text(encoding="utf-8"))
LETTERS = TABLE["header"]["letters"]


def test_table_header_records_the_generator():
    assert TABLE["header"]["node"].startswith("v") and TABLE["header"]["cldr"]
    assert set(TABLE["integers_0_to_1000"]) == set(i18n.LANGUAGES)


@pytest.mark.parametrize("lang", i18n.LANGUAGES)
def test_integers_0_to_1000_match_intl(lang):
    letters = TABLE["integers_0_to_1000"][lang]
    assert len(letters) == 1001
    inverse = {v: k for k, v in LETTERS.items()}
    wrong = [n for n in range(1001) if i18n.plural_category(n, lang) != inverse[letters[n]]]
    assert not wrong, wrong[:10]


@pytest.mark.parametrize("lang", i18n.LANGUAGES)
def test_decimals_match_intl(lang):
    inverse = {v: k for k, v in LETTERS.items()}
    for text, letter in TABLE["decimals"][lang].items():
        assert i18n.plural_category(float(text), lang) == inverse[letter], (lang, text)


@pytest.mark.parametrize("lang", i18n.LANGUAGES)
def test_declared_categories_equal_intl(lang):
    assert sorted(i18n.PLURAL_CATEGORIES_BY_LANG[lang]) == TABLE["categories"][lang]


def test_million_rule_for_romance_languages():
    # Not covered by the 0..1000 table: CLDR 42+ gives "many" for exact millions in es/it/fr/pt.
    for lang in ("fr", "es", "it", "pt"):
        assert i18n.plural_category(1_000_000, lang) == "many"
        assert i18n.plural_category(1_500_000, lang) == "other"
    assert i18n.plural_category(1_000_000, "en") == "other"
